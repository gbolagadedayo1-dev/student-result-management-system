import express from "express";
import cors from "cors";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import { env } from "./config/env.js";
import authRoutes from "./routes/auth.js";
import studentRoutes from "./routes/students.js";
import resultRoutes from "./routes/results.js";
import analyticsRoutes from "./routes/analytics.js";
import transcriptRoutes from "./routes/transcripts.js";
import academicRoutes from "./routes/academics.js";
import { errorHandler, notFound } from "./middleware/errors.js";

export const app = express();
app.set("trust proxy", 1);
app.disable("x-powered-by");
app.use(helmet({ crossOriginResourcePolicy: { policy: "cross-origin" } }));
app.use(cors({ origin: env.appOrigin.split(","), credentials: true, methods: ["GET", "POST", "PATCH", "PUT", "DELETE"] }));
app.use(express.json({ limit: "1mb" }));
app.use(express.urlencoded({ extended: false, limit: "1mb" }));
app.use("/api", rateLimit({ windowMs: 15 * 60 * 1000, limit: 500, standardHeaders: "draft-7", legacyHeaders: false }));
app.use("/api/auth", rateLimit({ windowMs: 15 * 60 * 1000, limit: 20 }), authRoutes);
app.get("/api/health", (_req, res) => res.json({ status: "ok", service: "maryresult-api", time: new Date().toISOString() }));
app.use("/api/students", studentRoutes);
app.use("/api/results", resultRoutes);
app.use("/api/analytics", analyticsRoutes);
app.use("/api/transcripts", transcriptRoutes);
app.use("/api/academics", academicRoutes);
app.use(notFound);
app.use(errorHandler);